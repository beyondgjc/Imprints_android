def make_pdf(lines, out):
    per = LINES_PER_PAGE
    need = PAGES_EACH_SIDE * per
    if len(lines) < need * 2:
        print(f'⚠️ 文档仅 {len(lines)} 行，不足 60 页所需 {need*2} 行')

    # 官方规则（《计算机软件著作权登记办法》第十条）：
    # 整个文档不到 60 页的，应当提交整个文档 —— 此时不存在「前后各30 页」，
    # 直接把全部行排出即可，不能为了凑满60 页重复内容。
    if len(lines) <= need * 2:
        pages = [lines[i * per:(i + 1) * per] for i in range((len(lines) + per - 1) // per)]
    else:
        head = lines[:need]
        tail = lines[-need:]
        pages = [head[i * per:(i + 1) * per] for i in range(PAGES_EACH_SIDE)]
        pages += [tail[i * per:(i + 1) * per] for i in range(PAGES_EACH_SIDE)]

    pdfmetrics.registerFont(UnicodeCIDFont('STSong-Light'))
    c = canvas.Canvas(out, pagesize=A4)
    w, h = A4
    left, right = 22 * mm, 18 * mm
    top = 24 * mm
    size, leading = 10.5, 15.2

    n = len(pages)
    for i, page in enumerate(pages, 1):
        c.setFont('STSong-Light', 11)
        c.drawString(left, h - 15 * mm, f'{SOFTWARE_NAME}（{VERSION}）软件设计说明书')
        c.setFont('STSong-Light', 10)
        # 页码标在右上角（官方要求：「申请文件各部分应当分别用数字顺序在右上角标注页码」）
        c.drawRightString(w - right, h - 10 * mm, str(i))
        c.setLineWidth(0.4)
        c.line(left, h - 17 * mm, w - right, h - 17 * mm)

        c.setFont('STSong-Light', 9)
        c.drawString(left, 12 * mm, f'著作权人：{COPYRIGHT_OWNER}')
        c.drawRightString(w - right, 12 * mm, PACKAGE)

        c.setFont('STSong-Light', size)
        y = h - top
        for ln in page:
            # 制表符展开为全角空格，避免显示为方块
            text = ln.replace('\t', '　').replace('─', '-').replace('┌', '+').replace('┐', '+')
            text = text.replace('└', '+').replace('┘', '+').replace('├', '+').replace('┤', '+')
            text = text.replace('│', '|').replace('═', '=')
            c.drawString(left, y, text[:78])
            y -= leading
        c.showPage()

    c.save()
    return n, len(lines)


